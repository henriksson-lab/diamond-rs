#!/usr/bin/env python3
"""Generate narrow CRT declarations from maintained headers, never FILE layouts.

Generation tool only: normal Rust/package builds do not invoke clang or need a
Windows SDK. Pass a matching maintained CRT include directory. The checked-in
provenance records actual inputs and target declarations. No C object is built.
"""
import argparse
import hashlib
import json
import pathlib
import re
import subprocess

p = argparse.ArgumentParser()
p.add_argument('--clang', default='clang')
p.add_argument('--rustfmt', default='rustfmt')
p.add_argument('--libc-windows', type=pathlib.Path, required=True)
p.add_argument('--include', type=pathlib.Path, required=True)
p.add_argument('--output', type=pathlib.Path, required=True)
p.add_argument('--provenance', type=pathlib.Path, required=True)
a = p.parse_args()
symbols = ['_fseeki64', '_ftelli64', '_errno', '_get_errno', '__acrt_iob_func', '_setmaxstdio', '_wfopen']
maintained_symbols = ['_wopen', '_wstat64']
targets = ['x86_64-pc-windows-msvc', 'i686-pc-windows-msvc', 'x86_64-w64-windows-gnu', 'i686-w64-windows-gnu', 'aarch64-w64-windows-gnu']
source = b'#include <stdio.h>\n#include <errno.h>\n#include <io.h>\n#include <sys/stat.h>\n'
proof = {'generator': 'translation/generate_windows_crt_bindings.py', 'clang_version': subprocess.check_output([a.clang, '--version']).decode(), 'headers': {}, 'targets': {}, 'header_provenance': 'Maintained MinGW-w64 distribution headers; stdio.h public-domain notice retained upstream. Only compiler-extracted declarations are emitted.', 'primary_sources': ['https://raw.githubusercontent.com/mingw-w64/mingw-w64/master/mingw-w64-headers/crt/stdio.h', 'https://learn.microsoft.com/en-us/cpp/c-runtime-library/reference/fseek-fseeki64?view=msvc-170', 'https://learn.microsoft.com/en-us/cpp/c-runtime-library/reference/ftell-ftelli64?view=msvc-170', 'https://learn.microsoft.com/en-us/cpp/c-runtime-library/reference/get-errno?view=msvc-170', 'https://learn.microsoft.com/en-us/cpp/c-runtime-library/reference/setmaxstdio?view=msvc-170', 'https://doc.rust-lang.org/reference/linkage.html#static-and-dynamic-c-runtimes'], 'scope': 'Compiler-generated function declarations only; FILE remains opaque libc::FILE. No fpos_t/layout is generated. MSVC ARM64 header/link/runtime validation remains pending; installed MinGW8 varargs headers reject that MSVC target.', 'linking': 'No explicit CRT DLL import: Rust/libc target CRT selection supplies symbols, including crt-static. Do not pass a FILE between different CRT instances.'}
for name in ['stdio.h', 'errno.h', 'corecrt.h', 'vadefs.h', '_mingw.h', 'io.h', 'sys/stat.h', '_mingw_stat64.h']:
    f = a.include / name
    proof['headers'][str(f)] = hashlib.sha256(f.read_bytes()).hexdigest()

def ast(target, name):
    argv = [a.clang, '--target=' + target, '-isystem', str(a.include), '-x', 'c', '-fsyntax-only', '-Xclang', '-ast-dump=json', '-Xclang', '-ast-dump-filter', '-Xclang', name, '-']
    result = subprocess.run(argv, input=source, stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)
    remaining = result.stdout.decode()
    declarations = []
    decoder = json.JSONDecoder()
    while remaining.strip():
        node, end = decoder.raw_decode(remaining.lstrip())
        remaining = remaining.lstrip()[end:]
        if node.get('name') == name:
            declarations.append(node)
    return argv, declarations

signatures = None
for target in targets:
    argv, typedefs = ast(target, 'errno_t')
    assert any(n.get('kind') == 'TypedefDecl' and n['type']['qualType'] == 'int' for n in typedefs)
    calls = {}
    for name in symbols + maintained_symbols:
        argv, nodes = ast(target, name)
        node = next(n for n in nodes if n.get('kind') == 'FunctionDecl')
        assert '__attribute__((cdecl))' in node['type']['qualType']
        signature = node['type']['desugaredQualType']
        calls[name] = {'argv': argv, 'signature': signature, 'mangled_name': node.get('mangledName'), 'parameters': [n['type']['qualType'] for n in node.get('inner', []) if n.get('kind') == 'ParmVarDecl']}
    current = {name: d['signature'] for name, d in calls.items()}
    if signatures is None:
        signatures = current
    assert current == signatures, (target, current)
    proof['targets'][target] = calls

# Closed type translation: fail generation if the maintained headers acquire
# any type outside this audited scalar/opaque-pointer surface.
types = {'int': 'libc::c_int', 'unsigned int': 'libc::c_uint', 'long long': 'i64', 'errno_t': 'libc::errno_t', 'int *': '*mut libc::c_int', 'FILE *': '*mut libc::FILE', 'const wchar_t *restrict': '*const libc::wchar_t'}
lines = ['// @generated by translation/generate_windows_crt_bindings.py; do not edit.', '// Header hashes, clang targets and declarations: translation/windows_crt_bindings.json.', '// No FILE/fpos_t layout; symbols resolve through the CRT selected by Rust/libc.', '#![allow(dead_code)]', '', 'extern "C" {']
for name in symbols:
    signature = signatures[name]
    match = re.fullmatch(r'(.+?)\((.*)\)', signature)
    result = types[match[1].strip()]
    args = match[2].strip()
    params = [] if args in ['', 'void'] else [types[x.strip()] for x in args.split(',')]
    lines.append('    pub(crate) fn ' + name + '(' + ', '.join('arg' + str(i) + ': ' + t for i, t in enumerate(params)) + ') -> ' + result + ';')
lines.extend(['}', ''])
# libc already maintains wopen/wstat; verify these declarations rather than
# duplicate their ABI or recreate the struct used by wstat.
assert signatures['_wopen'] == 'int (const wchar_t *, int, ...)'
assert signatures['_wstat64'] == 'int (const wchar_t *, struct _stat64 *)'
layout_targets = {}
layouts = []
for target in targets:
    argv = [a.clang, '--target=' + target, '-isystem', str(a.include), '-x', 'c', '-fsyntax-only', '-Xclang', '-fdump-record-layouts-complete', '-']
    output = subprocess.check_output(argv, input=source).decode()
    match = re.search(r'0 \| struct _stat64\n(.*?)\[sizeof=(\d+), align=(\d+)\]', output, flags=re.S)
    assert match, target
    fields = [(name, int(offset)) for offset, name in re.findall(r'^\s*(\d+) \|\s+[^\n]*?\b(st_\w+)\s*$', match[1], flags=re.M)]
    assert len(fields) == 11, fields
    layout = {'size': int(match[2]), 'alignment': int(match[3]), 'fields': fields}
    layouts.append(layout)
    layout_targets[target] = {'argv': argv, 'extracted_layout': layout}
assert all(item == layouts[0] for item in layouts)
proof['maintained_libc_stat64_layout_check'] = layout_targets
libc_text = a.libc_windows.read_text()
assert re.search(r'#\[link_name = "_wopen"\]\s*pub fn wopen\(path: \*const wchar_t, oflag: c_int, \.\.\.\) -> c_int;', libc_text)
assert re.search(r'#\[link_name = "_wstat64"\]\s*pub fn wstat\(path: \*const wchar_t, buf: \*mut stat\) -> c_int;', libc_text)
assert 'pub type wchar_t = u16;' in libc_text
proof['windows_filename_policy'] = {'conversion': 'Rust Unicode str/path to NUL-terminated UTF16 at actual named fopen/open/stat boundaries, using matching wide CRT calls. No pathname reopen or stream-mode change.', 'strict_source_scope': 'Same OS files for Source ACP-representable filenames; Source narrow-argv/ACP diagnostic-byte equivalence remains unverified.', 'native_extension': 'Unicode filenames outside the Source narrow argv codepage are a deliberate safe Rust extension; not claimed identical to Source lossy/unrepresentable argv.', 'runtime_status': 'Windows runtime validation pending; header generation and compile-time layout assertions are not runtime proof.', 'references': ['https://learn.microsoft.com/en-us/cpp/c-runtime-library/reference/fopen-wfopen?view=msvc-170', 'https://learn.microsoft.com/en-us/windows/apps/design/globalizing/use-utf8-code-page']}
proof['maintained_bindings'] = {'_wopen': 'libc::wopen', '_wstat64': 'libc::wstat; storage libc::stat, not a generated struct', 'libc_header': str(a.libc_windows), 'libc_header_sha256': hashlib.sha256(a.libc_windows.read_bytes()).hexdigest(), 'layout_policy': 'Generated size/alignment/field-offset compile-time assertions verify maintained libc::stat against compiler-extracted _stat64; no alternate struct.'}
lines += ['// Fail compilation rather than pass a mismatched maintained libc layout.', 'const _: () = {', '    assert!(std::mem::size_of::<libc::stat>() == ' + str(layouts[0]['size']) + ');', '    assert!(std::mem::align_of::<libc::stat>() == ' + str(layouts[0]['alignment']) + ');']
for name, offset in layouts[0]['fields']:
    lines += ['    assert!(std::mem::offset_of!(libc::stat, ' + name + ') == ' + str(offset) + ');']
lines += ['};', '']
a.output.write_text('\n'.join(lines))
subprocess.run([a.rustfmt, '--edition', '2021', str(a.output)], check=True)
proof['format_command'] = [a.rustfmt, '--edition', '2021', str(a.output)]
proof['generated_sha256'] = hashlib.sha256(a.output.read_bytes()).hexdigest()
proof['generator_sha256'] = hashlib.sha256(pathlib.Path(__file__).read_bytes()).hexdigest()
a.provenance.write_text(json.dumps(proof, indent=2) + '\n')
