#!/usr/bin/env python3
"""Generate standard-stream pointer declarations, not FILE layouts or SDK code.

Inputs are maintained stdio headers. Only canonical FILE-pointer declarations
are accepted; changed qualifiers/declarations fail closed. Clang validates the
installed GNU declarations. Apple declarations come directly from a versioned
Apple Libc header and do not require an SDK during normal or package builds.
"""
import argparse
import hashlib
import json
import pathlib
import re
import subprocess

p = argparse.ArgumentParser()
p.add_argument('--gnu-header', type=pathlib.Path, required=True)
p.add_argument('--musl-header', type=pathlib.Path, required=True)
p.add_argument('--apple-header', type=pathlib.Path, required=True)
p.add_argument('--clang', default='clang')
p.add_argument('--rustfmt', default='rustfmt')
p.add_argument('--output', type=pathlib.Path, required=True)
p.add_argument('--provenance', type=pathlib.Path, required=True)
a = p.parse_args()
profiles = [
    ('gnu', a.gnu_header, ['stdout', 'stderr'], False, 'all(target_os = "linux", target_env = "gnu")'),
    ('musl', a.musl_header, ['stdout', 'stderr'], True, 'all(target_os = "linux", target_env = "musl")'),
    ('darwin', a.apple_header, ['__stdoutp', '__stderrp'], False, 'target_vendor = "apple"'),
]
proof = {'generator': 'translation/generate_posix_stdio_bindings.py', 'scope': 'Only opaque FILE-pointer variable declarations; no FILE/fpos_t layout, no fdopen, no stream ownership or SDK requirement in package builds.', 'profiles': {}, 'primary_sources': ['https://sourceware.org/git/?p=glibc.git;a=blob;f=libio/stdio.h', 'https://git.musl-libc.org/cgit/musl/tree/include/stdio.h', 'https://raw.githubusercontent.com/apple-oss-distributions/Libc/Libc-1439.141.1/include/stdio.h'], 'license_scope': 'No implementation or struct layout copied. Header inputs retain their upstream license notices; generated declarations describe public pointer ABI only.'}
lines = ['// @generated by translation/generate_posix_stdio_bindings.py; do not edit.', '// Exact source declarations/hashes: translation/posix_stdio_bindings.json.', '// FILE is the opaque maintained libc type. These symbols are borrowed only.', '#![allow(dead_code)]', '']
for name, path, symbols, const_pointer, cfg in profiles:
    text = re.sub(r'/\*.*?\*/', '', path.read_text(), flags=re.S)
    declarations = []
    for symbol in symbols:
        matches = re.findall(r'^\s*extern\s+FILE\s*\*\s*(const\s+)?' + re.escape(symbol) + r'\s*;', text, flags=re.M)
        assert len(matches) == 1 and bool(matches[0].strip()) == const_pointer, (name, symbol, matches)
        declarations.append('extern FILE *' + ('const ' if const_pointer else '') + symbol + ';')
    proof['profiles'][name] = {'input_header': str(path), 'sha256': hashlib.sha256(path.read_bytes()).hexdigest(), 'exact_declarations': declarations, 'const_pointer': const_pointer, 'cfg': cfg}
    lines += ['#[cfg(' + cfg + ')]', 'mod ' + name + ' {', '    extern "C" {']
    for symbol in symbols:
        lines.append('        pub(super) static ' + ('' if const_pointer else 'mut ') + symbol + ': *mut libc::FILE;')
    lines += ['    }', '}', '']
# Type-check the GNU declarations using the actual installed header, without
# copying its FILE definition into any Rust output.
for symbol in ['stdout', 'stderr']:
    argv = [a.clang, '-x', 'c', '-fsyntax-only', '-Xclang', '-ast-dump=json', '-Xclang', '-ast-dump-filter', '-Xclang', symbol, '-']
    result = subprocess.run(argv, input=('#include "' + str(a.gnu_header.resolve()) + '"\n').encode(), stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)
    remaining = result.stdout.decode()
    found = []
    while remaining.strip():
        node, end = json.JSONDecoder().raw_decode(remaining.lstrip())
        remaining = remaining.lstrip()[end:]
        if node.get('kind') == 'VarDecl' and node.get('name') == symbol:
            assert node['type']['qualType'] == 'FILE *', node['type']
            found.append(node['type'])
    assert found
    proof['profiles']['gnu'].setdefault('clang_AST', {})[symbol] = {'argv': argv, 'types': found}
for function, index in [('stdout', 0), ('stderr', 1)]:
    lines += ['pub(crate) unsafe fn ' + function + '() -> *mut libc::FILE {']
    for name, _, symbols, _, cfg in profiles:
        lines += ['    #[cfg(' + cfg + ')]', '    { unsafe { ' + name + '::' + symbols[index] + ' } }']
    lines += ['}', '']
a.output.write_text('\n'.join(lines))
subprocess.run([a.rustfmt, '--edition', '2021', str(a.output)], check=True)
proof['format_command'] = [a.rustfmt, '--edition', '2021', str(a.output)]
proof['generated_sha256'] = hashlib.sha256(a.output.read_bytes()).hexdigest()
proof['generator_sha256'] = hashlib.sha256(pathlib.Path(__file__).read_bytes()).hexdigest()
a.provenance.write_text(json.dumps(proof, indent=2) + '\n')
